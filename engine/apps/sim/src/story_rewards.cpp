bool same_upper(std::string_view a, std::string_view upper_name) {
    if (a.size() != upper_name.size()) return false;
    for (size_t i = 0; i < a.size(); ++i)
        if (upper(a[i]) != upper_name[i]) return false;
    return true;
}
